def _claim(cid: str, *, title: str = "A claim", anchor: str = "a-claim", band: str = "ok-to-build") -> kb_index.Claim:
    return kb_index.Claim(
        node_type="claim",
        id=cid,
        title=title,
        canonical_path="vol1/topic/leaf.md",
        canonical_anchor=anchor,
        confidence=None,
        solidity=None,
        build_status=None,
        build_band=band,
        rationale="",
        depends_on_count=0,
        strengthen_by_count=0,
        citation_count=0,
    )


def _support(sid: str) -> kb_index.SupportNode:
    return kb_index.SupportNode(
        node_type="support",
        id=sid,
        title="A support",
        canonical_path="vol1/topic/sup.md",
        canonical_anchor="a-support",
        quality=None,
        solidity=None,
        build_band="do-not-build",
    )


def _experiment(eid: str) -> kb_index.ExperimentNode:
    return kb_index.ExperimentNode(
        node_type="experiment",
        id=eid,
        title="An experiment",
        canonical_path="vol1/topic/exp.md",
        canonical_anchor="an-experiment",
        status="run",
    )


def _framework(fid: str, node_type: str = "invariant") -> kb_index.FrameworkNode:
    return kb_index.FrameworkNode(
        node_type=node_type,
        id=fid,
        title="A framework rule",
        canonical_path="CLAUDE.md",
        canonical_anchor=fid.lower(),
    )


def _edge(source: str, target: str, **overrides) -> kb_index.DependsOnEdge:
    fields = {
        "source": source,
        "target": target,
        "target_kind": "claim",
        "target_solidity_recorded": None,
        "context": None,
        "relation": "depends",
        "strength": None,
        "fraction": None,
    }
    fields.update(overrides)
    return kb_index.DependsOnEdge(**fields)


def _sheet(nodes: Iterable[kb_index.GraphNode], edges: Iterable[kb_index.DependsOnEdge] = ()) -> layout.Sheet:
    return layout.place(model.build_graph(nodes=list(nodes), edges=list(edges)))


def _render(nodes, edges=(), *, link_base: str = "kb-root", foreign: Iterable[str] = ()) -> str:
    return svg.render(_sheet(nodes, edges), link_base=link_base, foreign=tuple(foreign))


# ---------------------------------------------------------------------------
# Reading a rendered document back
# ---------------------------------------------------------------------------


def _local(tag: str) -> str:
    """The tag without the namespace the parser resolves ``xmlns`` into."""
    return tag.rpartition("}")[2]


def _by_local(root: ET.Element, name: str) -> list[ET.Element]:
    return [element for element in root.iter() if _local(element.tag) == name]


def _node_groups(root: ET.Element) -> dict[str, ET.Element]:
    """Every node group, keyed by the id its first label line carries."""
    groups = [element for element in _by_local(root, "g") if element.get("class") == "node"]
    return {_by_local(group, "text")[0].text.split(" ")[0]: group for group in groups}


def _edge_lines(root: ET.Element) -> dict[tuple[str, str], ET.Element]:
    """Every stroke, keyed by the pair its tooltip head names.

    One ``polyline`` per edge however many layers it spans: an edge crossing
    layers is routed through a dummy in each, and the whole chain is one
    element.
    """
    out = {}
    for line in _by_local(root, "polyline"):
        head = _by_local(line, "title")[0].text.split(" — ")[0]
        source, _, target = head.partition(" → ")
        out[(source, target)] = line
    return out


def _hrefs(root: ET.Element) -> dict[str, str]:
    """Every link target, keyed by the id of the node group it wraps."""
    out = {}
    for anchor in _by_local(root, "a"):
        group = list(anchor)[0]
        out[_by_local(group, "text")[0].text.split(" ")[0]] = anchor.get("href")
    return out


