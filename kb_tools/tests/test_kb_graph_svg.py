def test_all_four_node_types_take_their_own_fill() -> None:
    claim, support, experiment, invariant, axiom = (
        _claim("clm-aa1111"),
        _support("sup-aa1111"),
        _experiment("exp-aa1111"),
        _framework("INVARIANT-S1"),
        _framework("axiom-1", "axiom"),
    )
    root = ET.fromstring(_render([claim, support, experiment, invariant, axiom]))
    fills = {node_id: _by_local(group, "rect")[0].get("fill") for node_id, group in _node_groups(root).items()}

    assert fills == {
        "clm-aa1111": style.BAND_PALETTE["ok-to-build"],
        "sup-aa1111": style.BAND_PALETTE["do-not-build"],
        "exp-aa1111": style.EXPERIMENT_FILL,
        "INVARIANT-S1": style.FRAMEWORK_FILL,
        "axiom-1": style.FRAMEWORK_FILL,
    }
    # A framework fill is deliberately not a rung of the ramp: bedrock is a
    # convention of the solidity rule, not a stored score.
    assert style.FRAMEWORK_FILL not in style.BAND_PALETTE.values()


