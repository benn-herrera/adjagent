"""Markup-level tests for ``kb_graph.svg``.

One section per clause of the row's done-condition.

**The golden's index is built at test time, never committed.** The
committed ``mini-kb`` fixture is copied to a temp directory, ``refresh`` runs
over the copy, and the sheet is rendered from what it emitted; only the ``.svg``
is committed. A committed ``.index/`` would be a derived artifact in the tree
with no freshness gate — the drift surface the canonical-direction rule exists
to prevent — and it could go stale against the fixture it derives from. Built
this way it cannot, and a change to an emitter's record shape surfaces as a
golden diff instead of hiding behind a frozen copy. :func:`render_mini_kb_golden`
and :func:`write_mini_kb_golden` are that helper, and ``just regenerate-mini-kb-golden``
runs through them so the recipe and this suite build the index the same way.

**The copy must carry the fixture's ``CLAUDE.md``** or the framework nodes it
declares never appear — the fixture hosts its invariants and axioms there, and a
golden rendered without them would be a smaller picture that still reproduced
itself forever.

The synthetic fixtures cover what ``mini-kb`` cannot: it carries no empty
``canonical_anchor`` and no hostile title, so those two are built here.
"""

