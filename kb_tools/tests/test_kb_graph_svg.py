_TESTS = Path(__file__).resolve().parent
#: The directory holding the ``kb_tools`` package — the refresh run's PYTHONPATH.
_PKG_PARENT = _TESTS.parents[1]
_PACKAGE = _PKG_PARENT / "kb_tools" / "kb_graph"
_MINI_KB = _TESTS / "fixtures" / "mini-kb"

#: The committed golden. Regenerated by :func:`write_mini_kb_golden`, never
#: hand-edited: a hand-authored golden is a byte-fidelity expectation placed on
#: inference, and this document is exactly the artifact that would expose it.
MINI_KB_GOLDEN = _TESTS / "fixtures" / "graph" / "mini-kb.svg"

#: Where the golden's links point, as repo-relative POSIX paths: from the
#: golden's own directory to the committed fixture it describes. Written as
#: paths rather than resolved absolutes so no machine-local prefix can reach an
#: output position — the sheet the test renders is built over a temp copy,
#: and a link into that copy would be a different document on every run.
_GOLDEN_LINK_BASE = svg.relative_link_base(
    kb_root=PurePosixPath("kb_tools/tests/fixtures/mini-kb"),
    sheet_dir=PurePosixPath("kb_tools/tests/fixtures/graph"),
)


# ---------------------------------------------------------------------------
# The golden-fixture helper
# ---------------------------------------------------------------------------


def _refresh(kb_root: Path) -> subprocess.CompletedProcess:
    """Run the refresh target's module over ``kb_root``, as ``test_refresh_index`` does."""
    return subprocess.run(
        [sys.executable, "-m", "kb_tools.refresh_kb_metadata", "--kb-root", str(kb_root)],
        cwd=_PKG_PARENT,
        env={**os.environ, "PYTHONPATH": str(_PKG_PARENT), "PYTHONDONTWRITEBYTECODE": "1"},
        capture_output=True,
        text=True,
        check=False,
    )


def render_mini_kb_golden() -> str:
    """The ``mini-kb`` sheet, from an index built over a temp copy of the fixture.

    The committed fixture is never mutated and the index it derives is never
    committed. The copy is a whole-tree copy, so it carries the fixture's
    ``CLAUDE.md`` — the framework nodes' authored home.
    """
    with tempfile.TemporaryDirectory() as workspace:
        kb_root = Path(workspace) / _MINI_KB.name
        shutil.copytree(_MINI_KB, kb_root)
        result = _refresh(kb_root)
        if result.returncode != 0:
            raise RuntimeError(f"refresh over the mini-kb copy failed:\n{result.stdout}\n{result.stderr}")

        index = kb_index.load(kb_root / ".index")
        graph = model.build_graph(nodes=index.all_nodes, edges=index.all_depends_on_edges)
        return svg.render(layout.place(graph), link_base=_GOLDEN_LINK_BASE)


def write_mini_kb_golden() -> Path:
    """Regenerate the committed golden. The one writer, following the write discipline."""
    MINI_KB_GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    MINI_KB_GOLDEN.write_text(render_mini_kb_golden(), encoding="utf-8", newline="\n")
    return MINI_KB_GOLDEN


@pytest.fixture(scope="module")
def mini_kb_renders() -> tuple[str, str]:
    """Two independent renders of the fixture — copy, refresh and all.

    Module-scoped: each render pays for a full refresh, and every question below
    reads the same pair rather than buying a run apiece.
    """
    return render_mini_kb_golden(), render_mini_kb_golden()


