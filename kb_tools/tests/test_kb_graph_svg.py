def test_every_golden_link_resolves_from_the_sheets_own_directory_to_a_file_on_disk() -> None:
    """The whole claim, end to end: the golden's own directory plus the ``href``
    it emitted lands on the committed fixture's Markdown."""
    root = ET.fromstring(MINI_KB_GOLDEN.read_text(encoding="utf-8"))
    hrefs = _hrefs(root)

    assert len(hrefs) == 32
