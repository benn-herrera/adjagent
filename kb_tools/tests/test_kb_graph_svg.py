# ---------------------------------------------------------------------------
# Mechanically: no string literal in the package composes markup
# ---------------------------------------------------------------------------
#
# The guard lives here rather than inside the package it sweeps, so it cannot
# match its own source. Its teeth are demonstrated below against a copy of the
# package with a literal planted in it — a sweep nobody has watched fail is a
# sweep that may be reaching nothing.

_MARKUP_OPENER = "<"


def _markup_literals(package: Path) -> tuple[list[Path], dict[str, list[str]]]:
    """Every string literal under ``package`` that opens markup, by file.

    Takes the tree under test as a parameter so the planted-literal run
    exercises this same discovery, not a second implementation of it.
    """
    sources = sorted(package.rglob("*.py"))
    found: dict[str, list[str]] = {}
    for path in sources:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        offenders = [
            node.value
            for node in ast.walk(tree)
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and _MARKUP_OPENER in node.value
        ]
        if offenders:
            found[path.name] = offenders
    return sources, found


def test_no_string_literal_in_the_package_contains_a_markup_opener() -> None:
    """The document is composed by the element tree, the XML declaration
    included — a processing-instruction node emits that, so this rule has no
    exception to remember. A hand-rolled escaper is an exhaustiveness obligation
    with no mechanical check; this is the check that keeps one from appearing."""
    sources, found = _markup_literals(_PACKAGE)

    assert {path.name for path in sources} >= {"model.py", "layout.py", "style.py", "svg.py"}
    assert found == {}


def test_the_guard_fails_on_a_planted_literal(tmp_path: Path) -> None:
    """The teeth. The plant goes into a copy of the real package, so a guard that
    had stopped reaching the package's files would fail here too."""
    planted = tmp_path / "kb_graph"
    shutil.copytree(_PACKAGE, planted, ignore=shutil.ignore_patterns("__pycache__"))
    (planted / "svg.py").write_text(
        (planted / "svg.py").read_text(encoding="utf-8") + '\n_PLANTED = "<svg>"\n',
        encoding="utf-8",
        newline="\n",
    )

    sources, found = _markup_literals(planted)

    assert {path.name for path in sources} == {path.name for path in _PACKAGE.rglob("*.py")}
    assert found == {"svg.py": ["<svg>"]}


# ---------------------------------------------------------------------------
# The numeric contract
# ---------------------------------------------------------------------------

#: Every attribute whose value is geometry. ``viewBox`` carries four tokens and
#: ``points`` two per vertex, so the check splits on both separators the two use
#: and holds each token to the same rule. ``points`` is the one that would go
#: vacuous if it were left out: an edge's coordinates live nowhere else now that
#: a stroke is a chain rather than an ``x1``/``y1``/``x2``/``y2`` line.
_INTEGER_ATTRIBUTES = ("viewBox", "points", "width", "height", "x", "y", "stroke-width", "font-size")
_INTEGER = re.compile(r"^-?(0|[1-9][0-9]*)$")
_GEOMETRY_SEPARATOR = re.compile(r"[\s,]+")

#: The hop arc, the single non-integral geometry: every value three decimals,
#: and the sweep flag a constant because the bulge rule has no cases.
_ARC = re.compile(r"^M (-?\d+\.\d{3}) (-?\d+\.\d{3}) A (\d+\.\d{3}) (\d+\.\d{3}) 0 0 1 (-?\d+\.\d{3}) (-?\d+\.\d{3})$")


def test_every_emitted_coordinate_in_the_golden_is_an_integer() -> None:
    root = ET.fromstring(MINI_KB_GOLDEN.read_text(encoding="utf-8"))
    checked = 0
    for element in root.iter():
        for name in _INTEGER_ATTRIBUTES:
            value = element.get(name)
            if value is None:
                continue
            for token in _GEOMETRY_SEPARATOR.split(value):
                assert _INTEGER.match(token), f"{_local(element.tag)}/{name} is {value!r}"
                checked += 1
    assert checked > 0


def test_every_arc_value_in_the_golden_carries_exactly_three_decimals() -> None:
    arcs = [
        element.get("d") for element in _by_local(ET.fromstring(MINI_KB_GOLDEN.read_text(encoding="utf-8")), "path")
    ]

    assert arcs
    for data in arcs:
        assert _ARC.match(data), data


def test_the_number_formatter_rounds_once_and_never_emits_a_signed_zero() -> None:
    """The formatter is the single place rounding happens, applied at emission
    after all the arithmetic."""
    assert svg.format_number(-24) == "-24"
    assert svg.format_number(0) == "0"
    # A crossing point arrives as an exact Fraction, which is what makes the
    # rounding one act rather than an accumulation of intermediate ones.
    assert svg.format_number(Fraction(1, 3)) == "0.333"
    assert svg.format_number(Fraction(-1, 3)) == "-0.333"
    assert svg.format_number(-0.0001) == "0.000"


def test_every_hop_arc_bridges_toward_screen_up() -> None:
    """The bulge is a screen fact and not an edge-local one.

    A fixed rotation of the hopping edge's own direction has constant handedness
    *relative to that edge*, so it flips in screen terms whenever the edge does:
    every hop on a right-to-left edge dips downward instead of bridging. Ordering
    the arc's two endpoints by screen x first is what makes the one rule serve
    both — the arc always runs left to right, so the constant sweep flag always
    bulges it upward.

    Four premises and four dependents, every pair joined: a shape that carries
    crossings no in-layer order can remove, and — the point of *four* — crossings
    whose higher-key edge is one of the right-to-left ones.
    """
    low = [f"clm-ll000{n}" for n in range(4)]
    high = [f"clm-uu000{n}" for n in range(4)]
    sheet = _sheet([_claim(cid) for cid in (*low, *high)], [_edge(up, down) for up in high for down in low])

    segments = {edge.key: edge.segments for edge in sheet.edges}
    hopped = [segments[hop.hopping][hop.hopping_segment] for hop in sheet.hops]
    assert [
        segment for segment in hopped if segment.end.x < segment.start.x
    ], "the fixture must carry the case the ordering exists for"

    root = ET.fromstring(svg.render(sheet, link_base="."))
    arcs = [_ARC.match(element.get("d")) for element in _by_local(root, "path")]
    assert arcs and all(arcs)
    for arc in arcs:
        start_x, start_y, _, _, end_x, end_y = (float(group) for group in arc.groups())
        # Ordered by screen x, tie-broken by y — and the sweep flag the pattern
        # pins is what turns that into a bulge on the upper side of the chord.
        assert (start_x, start_y) < (end_x, end_y)


def test_a_crossing_draws_one_arc_on_the_higher_key_edge() -> None:
    """Two edges built to cross, at the markup level: the glyph is centred on the
    crossing point and its endpoints sit one hop radius either side along the
    hopping edge. Which way it bulges from there is the test above.

    Every pair is joined, so the crossing is one the in-layer sweep cannot
    remove — a hand-built reversal is what the sweep is for.
    """
    left, right = "clm-aa0001", "clm-aa0002"
    upper_left, upper_right = "clm-bb0001", "clm-bb0002"
    sheet = _sheet(
        [_claim(cid) for cid in (left, right, upper_left, upper_right)],
        [_edge(upper, lower) for upper in (upper_left, upper_right) for lower in (left, right)],
    )
    assert len(sheet.hops) == 1

    root = ET.fromstring(svg.render(sheet, link_base="kb-root"))
    arcs = _by_local(root, "path")
    assert len(arcs) == 1

    hop = sheet.hops[0]
    match = _ARC.match(arcs[0].get("d"))
    assert match, arcs[0].get("d")
    start_x, start_y, radius, _, end_x, end_y = (float(group) for group in match.groups())
    assert radius == float(style.HOP_RADIUS)
    # The chord's midpoint is the crossing point, and its half-length the radius.
    assert (start_x + end_x) / 2 == pytest.approx(float(hop.x))
    assert (start_y + end_y) / 2 == pytest.approx(float(hop.y))
    # Three decimals per endpoint is the whole tolerance here: the arithmetic is
    # exact until the formatter, and the formatter is the only thing rounding.
    assert ((end_x - start_x) ** 2 + (end_y - start_y) ** 2) ** 0.5 == pytest.approx(2 * style.HOP_RADIUS, abs=0.002)
    # The arc is drawn on the hopping edge, in the hopping edge's own colour.
    assert arcs[0].get("stroke") == _edge_lines(root)[hop.hopping].get("stroke")


